// Rebuild only this reviewed import batch. No network or remote database writes.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';

const root = new URL('../', import.meta.url);
const batch = JSON.parse(readFileSync(new URL('catalogue-imports/2026-09-27.json', root), 'utf8'));
const quote = value => "'" + String(value).replaceAll("'", "''") + "'";

// Stable IDs prevent duplicate imports while leaving subsequent admin edits intact.
export function productId(key) {
  const bytes = createHash('sha256').update('fcc:catalogue:2026-09-27:' + key).digest().subarray(0, 16);
  bytes[6] = (bytes[6] & 15) | 64;
  bytes[8] = (bytes[8] & 63) | 128;
  const hex = bytes.toString('hex');
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
}

const additionsPath = new URL('catalogue-imports/reviewed-image-additions.json', root);
const additions = existsSync(additionsPath) ? JSON.parse(readFileSync(additionsPath, 'utf8')) : [];
const urls = [...new Set([...batch.products.flatMap(p => p.colours.map(c => c.source_image_url)), ...additions.map(image => image.url)].filter(Boolean))].sort();
const origins = [...new Set(['https://canada.beaulieucanada.com', ...urls.map(url => new URL(url).origin)])].sort();
for (const url of urls) {
  if (!/^https:\/\/(shawfloors\.widen\.net\/content\/|torlys\.com\/wp-content\/uploads\/|s7d[14]\.scene7\.com\/is\/image\/|res\.cloudinary\.com\/gh\/image\/|www\.vifloor\.com\/wp-content\/uploads\/|www\.shnierflooring\.ca\/catalog\/items\/|scrl\.img\.trykcloudstatic\.com\/designs\/|www\.pentzcommercial\.com\/wp-content\/uploads\/|cdn\.msisurfaces\.com\/images\/|www\.biyorkcanada\.com\/cdn\/shop\/|cdn\.bfldr\.com\/PMOA7OGQ\/|forbo\.azureedge\.net\/productimages\/)/.test(url)) {
    throw new Error('Review the new manufacturer image origin before adding it: ' + url);
  }
}
writeFileSync(new URL('server/manufacturer-images.js', root), `// Generated by tools/build-catalogue-import.mjs. Exact reviewed URLs only.\nconst images = new Set(${JSON.stringify(urls, null, 2)});\n\nexport const manufacturerImageOrigins = ${JSON.stringify(origins)};\n\nexport function isManufacturerImage(url) {\n  return typeof url === 'string' && (images.has(url) || /^https:\\/\\/canada\\.beaulieucanada\\.com\\/images\\/5436-1\\/Thumb_Hires-5436-(14312|16855|16986|84199|86583|89056|89823|19204|84294)\\.jpg\\?_w=600$/.test(url));\n}\n`);

const { record } = await import('../server/validation.js');
if (new Set(batch.products.map(p => p.key)).size !== batch.products.length) throw new Error('Duplicate product key.');
const sql = [
  '-- Reviewed catalogue batch, 2026-09-27. All products start as drafts.',
  '-- Sources, missing images and review notes: catalogue-imports/2026-09-27.json.',
  '-- Re-running does not overwrite products, publish drafts or change existing edits.',
  "INSERT INTO categories (id, name, slug, sort_order) VALUES ('rugs', 'Area Rugs', 'rugs', 15) ON CONFLICT(id) DO NOTHING;",
  "INSERT INTO categories (id, name, slug, sort_order) VALUES ('linoleum', 'Linoleum', 'linoleum', 65) ON CONFLICT(id) DO NOTHING;",
  "INSERT INTO categories (id, name, slug, sort_order) VALUES ('commercial-matting', 'Commercial Matting', 'commercial-matting', 75) ON CONFLICT(id) DO NOTHING;"
];
for (const product of batch.products) {
  const data = record({ ...product, image_id: null, image_alt: '', price_cents: null, price_unit: '', featured: false, published: false }, 'products');
  const keys = ['id', ...Object.keys(data)];
  const values = [productId(product.key), ...Object.values(data)].map(value => value === null ? 'NULL' : typeof value === 'number' ? String(value) : quote(value));
  sql.push(`\n-- ${product.brand}: ${product.name}\nINSERT INTO products (${keys.join(', ')})\nSELECT ${values.join(',\n       ')}\nWHERE NOT EXISTS (SELECT 1 FROM products WHERE lower(brand) = lower(${quote(product.brand)}) AND lower(name) = lower(${quote(product.name)}))\nON CONFLICT(id) DO NOTHING;`);
}
writeFileSync(new URL('migrations/0008_reviewed_catalogue_batch.sql', root), sql.join('\n') + '\n');
console.log(`Prepared ${batch.products.length} drafts, ${batch.products.reduce((n, p) => n + p.colours.length, 0)} colours and ${urls.length} external image URLs. No remote changes.`);
